# gen_forwarders.py <system dll> <arch> <out.h>: writes linker /export pragmas that forward every export of
# a system DLL (by name, keeping its ordinal; NONAME exports by ordinal) to the system copy by absolute path
# (\\.\GLOBALROOT\SystemRoot\System32 for x64, SysWOW64 for x86), so a shim with the same name in the game
# folder behaves exactly like the system DLL without loading itself again.
import os
import struct
import sys


def exports(path):
    d = open(path, 'rb').read()
    pe = struct.unpack_from('<I', d, 0x3c)[0]
    nsec = struct.unpack_from('<H', d, pe + 6)[0]
    optsz = struct.unpack_from('<H', d, pe + 20)[0]
    opt = pe + 24
    magic = struct.unpack_from('<H', d, opt)[0]
    ddir = opt + (112 if magic == 0x20b else 96)
    exp_rva, exp_size = struct.unpack_from('<II', d, ddir)
    secs = []
    for i in range(nsec):
        s = pe + 24 + optsz + i * 40
        vsize, va, rawsize, rawptr = struct.unpack_from('<IIII', d, s + 8)
        secs.append((va, max(vsize, rawsize), rawptr))

    def off(rva):
        for va, size, raw in secs:
            if va <= rva < va + size:
                return rva - va + raw
        raise ValueError('rva %x' % rva)

    e = off(exp_rva)
    base, nfunc, nname, afunc, aname, aord = struct.unpack_from('<IIIIII', d, e + 16)
    named = {}
    for i in range(nname):
        nrva = struct.unpack_from('<I', d, off(aname) + 4 * i)[0]
        idx = struct.unpack_from('<H', d, off(aord) + 2 * i)[0]
        o = off(nrva)
        named[idx] = d[o:d.index(b'\0', o)].decode('ascii')
    out = []
    for idx in range(nfunc):
        frva = struct.unpack_from('<I', d, off(afunc) + 4 * idx)[0]
        if frva == 0:
            continue
        out.append((base + idx, named.get(idx)))
    return out


def main():
    dll, arch, out = sys.argv[1], sys.argv[2], sys.argv[3]
    name = os.path.splitext(os.path.basename(dll))[0].lower()
    sysdir = 'System32' if arch == 'x64' else 'SysWOW64'
    target = '\\\\\\\\.\\\\GLOBALROOT\\\\SystemRoot\\\\%s\\\\%s.dll' % (sysdir, name)
    lines = ['// generated by gen_forwarders.py from %s (%s) - do not edit' % (dll, arch)]
    for ordinal, fn in exports(dll):
        if fn:
            lines.append('#pragma comment(linker, "/export:%s=%s.%s,@%d")' % (fn, target, fn, ordinal))
        else:
            lines.append('#pragma comment(linker, "/export:__ord%d=%s.#%d,@%d,NONAME")' % (ordinal, target, ordinal, ordinal))
    open(out, 'w', newline='\n').write('\n'.join(lines) + '\n')
    print('%s: %d exports -> %s' % (dll, len(lines) - 1, out))


main()
